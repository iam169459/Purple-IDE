// ---------------------------------------------------------------------------
// GitHub auto-updates
// ---------------------------------------------------------------------------
//
// Updates are published to YOUR GitHub repository's releases. Configure it once,
// either in package.json -> build.publish { provider: "github", owner, repo },
// or with PURPLE_UPDATE_REPO="owner/repo".
//
// Ship a release with a token that can write to that repo:
//   GH_TOKEN=... npm run dist -- --publish always

interface UpdateRepo { owner: string; repo: string }

/**
 * Release manifest (version.json) generated by scripts/build-version-manifest.mjs
 * and attached to every release. It only carries policy: electron-updater
 * already knows which release is newest and how to download it.
 */
const CRITICAL_INSTALL_DELAY_MS = 5000;

let updateRepo: UpdateRepo | null = null;
let packagedFeed = false;
let manualUpdateCheck = false;
let checkInFlight = false;
let pendingRequiredUpdate = false;
let pendingVersion: string | null = null;
let pendingNotes: string | null = null;
let dirtyEditorCount = 0;
let dirtyWaitNotified = false;
let criticalInstallTimer: ReturnType<typeof setTimeout> | null = null;

function resolveUpdateRepo(): UpdateRepo | null {
  const candidates: string[] = [];
  const fromEnv = (process.env.PURPLE_UPDATE_REPO || '').trim();
  if (fromEnv) candidates.push(fromEnv);
  try {
    const pkgPath = path.join(app.getAppPath(), 'package.json');
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    const publish = pkg?.build?.publish;
    const config = Array.isArray(publish) ? publish[0] : publish;
    if (config?.owner && config?.repo) candidates.push(`${config.owner}/${config.repo}`);
  } catch {}
  for (const candidate of candidates) {
    const [owner, repo] = candidate.split('/').map(part => part.trim());
    if (!owner || !repo) continue;
    // Ignore the placeholder until build.publish points at a real repository.
    if (/^your[-_]?(github[-_]?)?(user(name)?|repo)$/i.test(owner)) continue;
    return { owner, repo };
  }
  return null;
}

function updatesSupported(): boolean {
  return app.isPackaged && (updateRepo !== null || packagedFeed);
}

function quitAndReinstall(silent = false) {
  setImmediate(() => {
    try {
      autoUpdater.quitAndInstall(silent, true);
    } catch (error) {
      console.error('quitAndInstall failed:', error);
    }
  });
}

function configureAutoUpdater() {
  updateRepo = resolveUpdateRepo();
  // electron-builder writes app-update.yml into the packaged resources from
  // build.publish; electron-updater reads it automatically when no feed is set.
  packagedFeed = app.isPackaged && fs.existsSync(path.join(process.resourcesPath, 'app-update.yml'));
  autoUpdater.autoDownload = true;
  autoUpdater.autoInstallOnAppQuit = true;
  autoUpdater.allowDowngrade = false;
  if (updateRepo) {
    autoUpdater.setFeedURL({ provider: 'github', owner: updateRepo.owner, repo: updateRepo.repo });
  }
}

function versionManifestUrl(): string | null {
  if (!updateRepo) return null;
  return `https://github.com/${updateRepo.owner}/${updateRepo.repo}/releases/latest/download/version.json`;
}

async function fetchVersionManifest(): Promise<VersionManifest | null> {
  const url = versionManifestUrl();
  if (!url) return null;
  try {
    const response = await fetch(`${url}?t=${Date.now()}`, {
      headers: { 'Cache-Control': 'no-cache' },
      signal: AbortSignal.timeout(6000),
    });
    if (!response.ok) return null;
    const data = await response.json();
    return data && typeof data === 'object' ? (data as VersionManifest) : null;
  } catch {
    return null;
  }
}

function notifyUpdate(title: string, body: string) {
  if (!Notification.isSupported()) return;
  try {
    new Notification({ title, body }).show();
  } catch {}
}

function clearCriticalInstallTimer() {
  if (criticalInstallTimer) {
    clearTimeout(criticalInstallTimer);
    criticalInstallTimer = null;
  }
}

/**
 * Required (critical) updates install without asking. They are held back while
 * any editor has unsaved changes, then applied after a short grace period so a
 * stray keystroke can still cancel the restart.
 */
function scheduleCriticalInstall() {
  if (!pendingRequiredUpdate) return;
  if (dirtyEditorCount > 0) {
    clearCriticalInstallTimer();
    if (!dirtyWaitNotified) {
      dirtyWaitNotified = true;
      notifyUpdate(
        'Critical update waiting',
        'Purple IDE will install it as soon as every open file is saved.',
      );
    }
    return;
  }
  if (criticalInstallTimer) return;
  dirtyWaitNotified = false;
  notifyUpdate(
    'Restarting to install critical update',
    `Purple IDE ${pendingVersion ?? ''} installs in ${Math.round(CRITICAL_INSTALL_DELAY_MS / 1000)} seconds.`,
  );
  criticalInstallTimer = setTimeout(() => {
    criticalInstallTimer = null;
    if (pendingRequiredUpdate && dirtyEditorCount === 0) quitAndReinstall(true);
  }, CRITICAL_INSTALL_DELAY_MS);
}

ipcMain.on('app:dirty-state', (_event, count: unknown) => {
  const next = typeof count === 'number' && Number.isFinite(count)
    ? Math.max(0, Math.floor(count))
    : 0;
  if (next === dirtyEditorCount) return;
  dirtyEditorCount = next;
  if (pendingRequiredUpdate) scheduleCriticalInstall();
});

async function showInstallPrompt(wasManual: boolean) {
  if (!mainWindow) return;
  const detail = [
    wasManual ? 'A new version has been downloaded.' : 'An update was downloaded in the background.',
    pendingNotes,
    'Install now, or choose Later to apply it when you quit.',
  ].filter(Boolean).join('\n\n');
  const { response } = await dialog.showMessageBox(mainWindow, {
    type: 'info',
    title: 'Update Ready',
    message: `Purple IDE ${pendingVersion ?? ''} is ready to install`,
    detail,
    buttons: ['Install Now', 'Later'],
    defaultId: 0,
    cancelId: 1,
  });
  if (response === 0) quitAndReinstall();
}

async function checkForUpdates(manual: boolean): Promise<{ success: boolean; version?: string | null; error?: string }> {
  if (!app.isPackaged) {
    if (manual) {
      await dialog.showMessageBox({
        type: 'info',
        title: 'Check for Updates',
        message: 'Updates are available in installed builds only',
        detail: `You are running development build ${app.getVersion()}. Package the app (npm run dist) and install it to receive updates from GitHub.`,
        buttons: ['OK'],
      });
    }
    return { success: false, error: 'Not a packaged build' };
  }
  if (!updateRepo && !packagedFeed) {
    if (manual) {
      await dialog.showMessageBox({
        type: 'info',
        title: 'Check for Updates',
        message: 'No update repository configured',
        detail: 'Set build.publish in package.json to { "provider": "github", "owner": "<you>", "repo": "<repo>" }, or set PURPLE_UPDATE_REPO="owner/repo", then rebuild.',
        buttons: ['OK'],
      });
    }
    return { success: false, error: 'No update repository configured' };
  }
  if (checkInFlight) return { success: true, version: pendingVersion };

  checkInFlight = true;
  manualUpdateCheck = manual;
  pendingRequiredUpdate = false;
  pendingNotes = null;

  const manifest = await fetchVersionManifest();
  pendingRequiredUpdate = isRequiredUpdate(manifest, app.getVersion());
  pendingNotes = typeof manifest?.notes === 'string' && manifest.notes ? manifest.notes : null;

  try {
    const result = await autoUpdater.checkForUpdates();
    return { success: true, version: result?.updateInfo?.version ?? null };
  } catch (error) {
    manualUpdateCheck = false;
    console.error('Check for update failed:', error);
    return { success: false, error: (error as Error).message };
  } finally {
    checkInFlight = false;
  }
}

autoUpdater.on('checking-for-update', () => {
  console.log('Checking for updates...');
});

autoUpdater.on('update-available', (info: { version?: string }) => {
  console.log('Update available:', info.version, pendingRequiredUpdate ? '(required)' : '');
});

autoUpdater.on('update-not-available', () => {
  console.log('No update available.');
  if (!manualUpdateCheck) return;
  manualUpdateCheck = false;
  void dialog.showMessageBox({
    type: 'info',
    title: 'Check for Updates',
    message: "You're up to date",
    detail: `Purple IDE ${app.getVersion()} is the latest version.`,
    buttons: ['OK'],
  });
});

autoUpdater.on('download-progress', (progress: { percent?: number }) => {
  console.log(`Update download: ${Math.round(progress.percent ?? 0)}%`);
});

autoUpdater.on('update-downloaded', (info: { version?: string }) => {
  pendingVersion = info.version ?? null;
  const wasManual = manualUpdateCheck;
  manualUpdateCheck = false;
  console.log('Update downloaded:', pendingVersion, pendingRequiredUpdate ? '(required)' : '');

  if (pendingRequiredUpdate) {
    // No permission prompt for required releases; see scheduleCriticalInstall.
    scheduleCriticalInstall();
    return;
  }

  void showInstallPrompt(wasManual);
});

autoUpdater.on('error', (err: Error) => {
  console.error('Update error:', err.message);
  if (!manualUpdateCheck) return;
  manualUpdateCheck = false;
  void dialog.showMessageBox({
    type: 'error',
    title: 'Update Error',
    message: 'Could not check for updates',
    detail: err.message,
    buttons: ['OK'],
  });
});

